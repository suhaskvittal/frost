#ifndef UTIL_NUMERICS_h
#define UTIL_NUMERICS_h

#include <cstdint>
#include <cstddef>

////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////

template <class T>
constexpr inline bool is_power_of_two(T n)
{
    return (n & (n-1)) == 0;
}

////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////

template <class T>
constexpr inline T ilog2(T n)
{
    if (n > 1)
        return 1+ilog2(n >> 1);
    else
        return 0;
}

////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////

template <class T>
constexpr inline T fast_mod(T x, T m)
{
    return is_power_of_two(m) ? (x & (m-1)) : (x % m);
}

template <class T>
constexpr inline void fast_increment_and_mod_inplace(T& x, T m)
{
    if (is_power_of_two(m))
    {
        x = (x+1) & (m-1);
    }
    else
    {
        ++x;
        if (x == m)
            x = 0;
    }
}

////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////

#endif   // UTIL_NUMERICS_h

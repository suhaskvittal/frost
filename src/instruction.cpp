#include "constants.h"

#include "instruction.h"
#include "trace/fmt.h"

#include <cstring>

////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////

Instruction::Instruction(const MemsimTraceFormat& blk)
{
    memcpy(&inst_num, blk.inst_num, sizeof(blk.inst_num));
    memcpy(&v_lineaddr, blk.v_lineaddr, sizeof(blk.v_lineaddr));
    is_store = blk.is_write;
}

////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////

bool
Instruction::is_mem_inst() const
{
    return true;
}

bool
Instruction::is_done() const
{
    return is_store ? (state == AccessState::IN_CACHE) : (state == AccessState::DONE);
}


size_t
permute_with_tag(size_t a, uint64_t x, size_t count, size_t offset)
{
    const uint64_t tag = cache_tag<LLCache>(x);
    return a ^ fast_mod(static_cast<size_t>(tag >> ilog2(offset)), count);
}

